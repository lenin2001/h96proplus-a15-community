#!/system/bin/sh
# Максимальная производительность для H96 Pro Plus.
#
# ⛔ ГЛАВНОЕ ПРО ЭТУ ПРИСТАВКУ: видеоядро НЕ РАБОТАЕТ. Драйвер panfrost
# загружен, но питание блока не поднимается:
#     panfrost d00c0000.gpu: shader power transition timeout
#     panfrost d00c0000.gpu: tiler  power transition timeout
#     panfrost d00c0000.gpu: l2     power transition timeout
# Поэтому SurfaceFlinger рисует через ANGLE поверх SwiftShader, то есть
# ВСЮ графику считает процессор. Отсюда приоритеты настройки: экономить
# работу отрисовки важнее, чем разгонять память или диск.
#
# ⛔⛔ 25.08.2026: ЭТО НЕ КОСМЕТИКА, А ВОПРОС ЗАГРУЗКИ ВООБЩЕ.
# Приставка ушла в перезагрузочную петлю — семь циклов подряд, каждый
# обрывался на 2-й минуте. Улики (dropbox на карте):
#     Blocked in handler on display thread (android.display) for 15s
#     ANR: com.android.systemui failed to complete startup
#     148% com.android.settings, 128% surfaceflinger
# Сторож Android считал медленную отрисовку зависанием и убивал
# system_server. Таймаут сторожа поднят патчем до 300 с, но правильнее
# ещё и снизить саму нагрузку — чем и занимается этот файл.
#
# Значения не выдуманы — под каждым написано, почему именно так.

log() { echo "[perf] $*"; }

# ── сброс счётчика неудачных загрузок ─────────────────────────────────────
# Загрузчик считает попытки старта Android файлами-флагами на загрузочном
# разделе карты и после двух неудач подряд грузит спасательный образ. Раз
# мы сюда дошли, система работоспособна — флаги надо снять, иначе пара
# обычных перезагрузок уведёт приставку в спасательный режим вместо кино.
# Дублирует такой же сброс в bootwatchdog: две независимые попытки лучше
# одной, а лишнее удаление отсутствующих файлов ничего не стоит.
log "снимаю счётчик неудачных загрузок"
mkdir -p /mnt/sdboot 2>/dev/null
umount /mnt/sdboot 2>/dev/null
if mount -t vfat -o rw /dev/block/mmcblk0p1 /mnt/sdboot 2>/dev/null; then
    rm -f /mnt/sdboot/TRY1 /mnt/sdboot/TRY2 2>/dev/null
    sync
    umount /mnt/sdboot 2>/dev/null
    log "счётчик снят"
else
    log "не удалось смонтировать загрузочный раздел — счётчик остался"
fi


# ---------------------------------------------------------------- анимации
# Самый крупный выигрыш. Каждая анимация при программной отрисовке — это
# десятки полноэкранных кадров, посчитанных на 8 ядрах A53.
#
# 25.08: было 0.5 (вдвое короче). Отключаю ПОЛНОСТЬЮ. Прежнее рассуждение
# «без анимаций интерфейс теряет отзывчивость на вид» верно для нормального
# железа, но здесь всё наоборот: анимация из десятков программно
# посчитанных кадров — это и есть та задержка, от которой интерфейс
# кажется мёртвым. Ноль means кадры вообще не считаются.
settings put global window_animation_scale 0
settings put global transition_animation_scale 0
settings put global animator_duration_scale 0
log "анимации отключены полностью"

# ---------------------------------------------------------------- разрешение
# Отрисовка процессором стоит пропорционально числу пикселей. 1080p — это
# 2,07 млн пикселей на кадр; 720p — 0,92 млн, то есть работы ВДВОЕ меньше.
# Видео это не касается: его декодирует железо, а вывод остаётся 1080p —
# уменьшается только разрешение, в котором рисуется интерфейс.
#
# Для приставки, назначение которой — смотреть кино, это правильный размен:
# интерфейс чуть менее чёткий, зато он наконец успевает.
# 213 dpi — штатная плотность для 720p ТВ (при 320 для 1080p).
# ⛔ 29.08: ПОДМЕНУ РАЗРЕШЕНИЯ УБРАЛИ. Она давала обратный эффект: при
# нестандартном размере интерфейса SurfaceFlinger обязан масштабировать
# каждый кадр, а аппаратные плоскости meson-drm масштаб не тянут —
# drm_hwcomposer отказывался от аппаратной композиции целиком
# (usesDeviceComposition=false), и ВСЁ, включая видео, рисовал процессор
# программным SwiftShader: 1080p давал ~10 кадров в минуту.
# На нативном 1920x1080 аппаратная композиция включается сама.
wm size reset 2>/dev/null
wm density reset 2>/dev/null
log "разрешение интерфейса нативное 1920x1080 (нужно для аппаратной композиции)"

# ---------------------------------------------------------------- процессор
# Регулятор schedutil поднимает частоту по нагрузке — на интерфейсе это
# даёт задержку в начале каждого действия. Приставка питается от сети,
# температура 43 °C при пределе троттлинга гораздо выше, поэтому держим
# постоянный максимум.
for p in /sys/devices/system/cpu/cpufreq/policy*; do
    [ -d "$p" ] || continue
    echo performance > "$p/scaling_governor" 2>/dev/null
done
for c in /sys/devices/system/cpu/cpu[0-9]*/cpufreq; do
    [ -d "$c" ] || continue
    echo performance > "$c/scaling_governor" 2>/dev/null
done
log "процессор: постоянный максимум ($(cat /sys/devices/system/cpu/cpu0/cpufreq/scaling_cur_freq 2>/dev/null) кГц)"

# ---------------------------------------------------------------- чтение с карты
# Система и приложения живут на SD-карте: у неё большая задержка на
# операцию, но приличная линейная скорость. Крупное упреждающее чтение
# заметно помогает и запуску приложений, и воспроизведению файлов.
echo 512 > /sys/block/mmcblk0/queue/read_ahead_kb 2>/dev/null
# bfq лучше держит отзывчивость под фоновой записью, чем mq-deadline
echo bfq > /sys/block/mmcblk0/queue/scheduler 2>/dev/null
log "карта: упреждающее чтение 512 КБ, планировщик $(cat /sys/block/mmcblk0/queue/scheduler 2>/dev/null | tr -d '\n')"

# ---------------------------------------------------------------- память
# swappiness уже 100 (см. init.h96proplus.rc): выгрузка в сжатую память
# дешевле, чем убийство процесса. Здесь только подтверждаем.
echo 100 > /proc/sys/vm/swappiness 2>/dev/null
# Кэш каталогов и инодов держим дольше — на карте это дорогие чтения
echo 50 > /proc/sys/vm/vfs_cache_pressure 2>/dev/null
log "память: swappiness 100, кэш ФС удерживается дольше"

# ---------------------------------------------------------------- частота экрана
# ⛔ Подстройка частоты под содержимое на этом железе ломает картинку:
# система переключала экран между 60 и 25 Гц десятки раз в минуту, и
# монитор при каждом переключении гас на секунду (наблюдалось 23.08).
settings put secure match_content_frame_rate 0
log "подстройка частоты экрана отключена"

# ---------------------------------------------------------------- сторож
# Дублируем правку таймаута настройкой: патч Watchdog.java задаёт значение
# по умолчанию, а эта строка переживёт откат патча при пересоздании дерева.
settings put global watchdog_timeout_millis 300000
log "таймаут сторожа Android: 300 с"

# ---------------------------------------------------------------- клавиатура
# Экранная клавиатура по умолчанию — LeanbackIME (D-pad-навигация пультом).
# Иначе фреймворк выбирает LatinIME (телефонная soft-keyboard): она
# всплывает, но пультом в её клавиши НЕ зайти — курсора/тача нет (05.09.2026).
# Действует на чистом /data; переживает откат дерева. Имя сервиса сверено:
# com.android.inputmethod.leanback/.service.LeanbackImeService (НЕ .ime.).
LBIME=com.android.inputmethod.leanback/.service.LeanbackImeService
if pm list packages 2>/dev/null | grep -q com.android.inputmethod.leanback; then
    settings put secure enabled_input_methods "com.android.inputmethod.latin/.LatinIME:$LBIME"
    settings put secure default_input_method "$LBIME"
    log "клавиатура по умолчанию: LeanbackIME"
fi

log "готово"
